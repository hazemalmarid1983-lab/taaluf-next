function toLevels(descriptions) {
  const levels = {};
  for (const key of ['0', '1', '2', '3']) {
    const raw = String(descriptions[key] ?? descriptions[Number(key)] ?? '');
    const stripped = raw.replace(/^(مستقر|متوسط|شديد جداً|شديد)\s*:\s*/, '');
    levels[key] = {
      label: LABELS[key],
      description: stripped,
    };
  }
  return levels;
}

function wrapItem(item) {
  const question = item.question || item.title;
  return {
    id: item.id,
    name: item.title,
    title: item.title,
    domain: item.domain,
    domain_en: DOMAIN_EN[item.domain],
    domain_raw: item.domain,
    question,
    description: question,
    levels: toLevels(item.descriptions),
    recommendation: item.referralRecommendation,
    autoGoal: item.autoGoal,
    referralRecommendation: item.referralRecommendation,
    weight: 1.0,
    ageBands: item.ageBands || ALL_BANDS,
    is_reverse: false,
  };
}

