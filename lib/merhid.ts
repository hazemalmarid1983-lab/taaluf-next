import type { PortalRole } from '@/lib/access';

export const MERHID_NAME = 'مرشد تآلف';

export function merhidSystemPrompt(scope: PortalRole | 'admin') {
  if (scope === 'admin') {
    return `أنت ${MERHID_NAME} في لوحة الإدارة العليا لمنصة تآلف.
يمكنك المساعدة بحرية في: تشغيل المنصة، الصياغة، الأفكار التقنية، المحتوى، السياسات، والدعم التشغيلي.
أجب بالعربية بوضوح. إن طُلب شيء خارج المنصة يمكنك المساعدة باختصار مع تذكير أنك مساعد إدارة تآلف.`;
  }

  if (scope === 'specialist') {
    return `أنت ${MERHID_NAME} — مساعد مقيد لمختصي منصة تآلف فقط.
نطاقك حصرياً: تقييم 24 مؤشراً، 8 مجالات، التصنيف، الأهداف التربوية، التقارير، استراتيجيات منزل/مدرسة، ومتابعة الطالب.
ارفض بأدب أي موضوع خارج مسار تآلف (أخبار، برمجة عامة، طب عام…).
ممنوع إصدار تشخيص طبي قاطع أو وصف علاج دوائي.
أجب بالعربية الفصحى الواضحة.`;
  }

  // parent
  return `أنت ${MERHID_NAME} — مساعد مبسّط لأولياء الأمور على منصة تآلف فقط.
اشرح نتائج التقييم بلغة ودية بسيطة، واقترح نشاطاً منزلياً قصيراً واحداً عند الحاجة، ووضّح متى يراجعون المختص.
ارفض أي موضوع خارج دعم الطفل عبر تآلف.
ممنوع التشخيص الطبي أو مقارنة الأطفال أو نصائح دوائية.
أجب بالعربية البسيطة الواضحة.`;
}

export function merhidLocalReply(
  scope: PortalRole | 'admin',
  message: string
): string {
  const q = message.trim();
  if (!q) return 'اكتب سؤالك وسأساعدك ضمن نطاق تآلف.';

  if (scope === 'admin') {
    return `【${MERHID_NAME} — وضع الإدارة الحر】\nبخصوص: «${q}»\nيمكنك من لوحة الإدارة متابعة البوابات والصلاحيات والمواعيد. للتشغيل: تأكد من NEXTAUTH وOPENAI_API_KEY وربط Airtable. إن رغبت بصياغة نص أو سياسة، حدّد المطلوب بدقة.`;
  }

  if (scope === 'specialist') {
    if (/تشخيص|دواء|طبيب نفسي/i.test(q)) {
      return `【${MERHID_NAME}】 أقدّم ملامح تربوية واستراتيجيات فقط — لا أصدر تشخيصاً طبياً ولا توصيات دوائية. ركّز على درجات المؤشرات وخطة أسبوعية واحدة قابلة للقياس.`;
    }
    if (/هدف|استراتيج|تقييم|مؤشر|تقرير/i.test(q)) {
      return `【${MERHID_NAME}】 ضمن مسار المختص: اختر هدفاً واحداً من المؤشرات ذات الدرجة ≥2، طبّقه أسبوعين مع توثيق بسيط، ثم أعد التقييم في الموعد المقترح. استخدم شاشة النتائج بعد إنهاء الاستبيان.`;
    }
    return `【${MERHID_NAME}】 سؤالك خارج نطاق مسار تآلف للمختص أو يحتاج ربطاً بنتيجة تقييم محددة. اسأل عن المؤشرات، الأهداف، التقرير، أو استراتيجية منزل/مدرسة.`;
  }

  if (/تشخيص|دواء|مريض/i.test(q)) {
    return `【${MERHID_NAME}】 لا أقدّم تشخيصاً أو أدوية. تآلف أداة تربوية توجيهية — راجع مختص المنصة للمتابعة.`;
  }
  if (/نتيج|تقييم|طفل|منزل|نشاط/i.test(q)) {
    return `【${MERHID_NAME}】 بعد دفع/تفعيل التقييم ستظهر النتائج والأهداف. في المنزل: نشاط قصير يومياً (5–10 دقائق) بنفس الروتين، وتعزيز فوري عند النجاح. للمتابعة التفصيلية راجع المختص أو احجز فريقاً متعدد التخصصات.`;
  }
  return `【${MERHID_NAME}】 أساعد فقط في شرح تقييم تآلف والأنشطة المنزلية البسيطة. صِغ سؤالك حول نتيجة طفلك أو نشاط منزلي.`;
}
