/** إزالة صياغات تشخيصية وإحالات طبية مباشرة */
export function sanitizeDiagnosticLanguage(text = '') {
  let out = String(text);
  const replacements: Array<[RegExp, string]> = [
    [/طفلك يعاني من اضطراب/gi, 'يظهر طفلك صعوبة في'],
    [/يعاني من اضطراب/gi, 'يواجه تحدياً في'],
    [/الطفل مصاب بالتوحد/gi, 'يظهر الطفل صعوبات في التواصل والتفاعل الاجتماعي'],
    [/مصاب بـ?التوحد/gi, 'يظهر صعوبات في التواصل والتفاعل الاجتماعي'],
    [/تشخيص التوحد/gi, 'ملامح سلوكية تحتاج دعماً تربوياً في التواصل والتفاعل'],
    [/يُشخص|يشخّص|يشخص/gi, 'يُوصَف تربوياً'],
    [/مراجعة طبيب نفسي/gi, 'استشارة مختص تربوي مؤهل'],
    [/مراجعة طبيب/gi, 'متابعة تربوية مع مختص مؤهل'],
    [/علاج دوائي|دواء|أدوية/gi, 'استراتيجية تربوية تدريجية'],
    [/تحويل (إلى|الى) عيادة/gi, 'خطة تدخل تربوي في الصف والمنزل'],
  ];
  for (const [re, to] of replacements) out = out.replace(re, to);
  return out;
}

export function sanitizeAiPayload<T extends Record<string, unknown>>(payload: T): T {
  const clone = structuredClone(payload) as Record<string, unknown>;
  const walk = (value: unknown): unknown => {
    if (typeof value === 'string') return sanitizeDiagnosticLanguage(value);
    if (Array.isArray(value)) return value.map(walk);
    if (value && typeof value === 'object') {
      const obj: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
        obj[k] = walk(v);
      }
      return obj;
    }
    return value;
  };
  return walk(clone) as T;
}
